"""Reports hub — the Home Assistant glue for the reporting framework (reports.py).

One manager per gateway. It owns an index of generated reports, renders PDFs / CSVs with the dependency-free
writer (pdfmini.py), writes them under ``www/milesight/reports/<year>/`` (served at ``/local/…``) and lists what
exists for the Reports page. Cold-chain reports are produced by the existing ComplianceManager and folded into
the same library, so the page shows every report type in one place.
"""
from __future__ import annotations

import re
from datetime import datetime, tzinfo
from typing import TYPE_CHECKING, Any

from . import reports as R
from .const import DOMAIN, STORAGE_VERSION
from .pdfmini import A4, Pdf, fit, text_width

if TYPE_CHECKING:
    from homeassistant.config_entries import ConfigEntry
    from homeassistant.core import HomeAssistant

SIGNAL_REPORTS = f"{DOMAIN}_reports_{{}}"
KEEP = 80                                   # library rows kept in the index

_STATUS_COLOUR = {"ok": "#2e7d32", "warn": "#e67e00", "error": "#c62828", "soon": "#6b7280"}


# --------------------------------------------------------------------------
# a compact report document: navy header band, section headings and tables
# --------------------------------------------------------------------------
def build_pdf(title: str, subtitle: str, period_label: str, sections: list[dict[str, Any]],
              *, author: str = "", status: tuple[str, str] | None = None) -> bytes:
    pdf = Pdf(title=title, author=author)
    W, H = A4
    M = 44
    ink, mute, line_c, band = "#1b1b1b", "#6b7280", "#e4e7eb", "#f1f3f5"
    st = {"page": None, "y": 0.0}

    def footers() -> None:
        for n, pg in enumerate(pdf.pages, 1):
            pg.line(M, H - 34, W - M, H - 34, line_c, 0.4)
            pg.text(M, H - 22, "Generated by Milesight LoRaWAN for Home Assistant", 7.5, color=mute)
            pg.text(W - M, H - 22, f"Page {n} of {len(pdf.pages)}", 7.5, color=mute, align="right")

    def new_page(first: bool = False) -> None:
        p = pdf.page()
        st["page"] = p
        if first:
            p.rect(0, 0, W, 74, fill="#0b3d62")
            p.text(M, 30, fit(title, 17, W - 2 * M - 150, True), 17, True, "#ffffff")
            p.text(M, 50, fit(subtitle, 10, W - 2 * M - 150), 10, color="#d6e4f0")
            p.text(M, 64, fit("Period: " + period_label, 9, W - 2 * M - 150), 9, color="#d6e4f0")
            if status is not None:
                lbl, col = status
                bw = text_width(lbl, 10, True) + 22
                p.rect(W - M - bw, 24, bw, 24, fill=col)
                p.text(W - M - bw / 2, 40, lbl, 10, True, "#ffffff", "center")
            st["y"] = 96.0
        else:
            st["y"] = 54.0

    def need(h: float) -> None:
        if st["y"] + h > H - 44:
            new_page()

    def heading(s: str) -> None:
        need(30)
        st["y"] += 8
        st["page"].text(M, st["y"] + 10, s, 11, True, ink)
        st["y"] += 16
        st["page"].line(M, st["y"], W - M, st["y"], line_c, 0.6)
        st["y"] += 4

    def table(cols: list[tuple[str, float, str]], rows: list[list[str]],
              row_colours: list[str | None] | None = None) -> None:
        def header() -> None:
            p = st["page"]
            p.rect(M, st["y"], W - 2 * M, 16, fill=band)
            x = M
            for ttl, w, al in cols:
                p.text(x + (w - 5 if al == "right" else 5), st["y"] + 11, ttl, 7.5, True, mute,
                       "right" if al == "right" else "left")
                x += w
            st["y"] += 16
        need(34)
        header()
        for i, r in enumerate(rows):
            if st["y"] + 14 > H - 44:
                new_page()
                header()
            p = st["page"]
            x = M
            colour = (row_colours[i] if row_colours else None) or ink
            for (ttl, w, al), cell in zip(cols, r):
                p.text(x + (w - 5 if al == "right" else 5), st["y"] + 10, fit(str(cell), 8, w - 10), 8,
                       color=colour, align="right" if al == "right" else "left")
                x += w
            st["y"] += 14
            p.line(M, st["y"], W - M, st["y"], line_c, 0.3)

    new_page(first=True)
    for sec in sections:
        heading(sec["heading"])
        if sec.get("note"):
            need(16)
            st["page"].text(M, st["y"] + 9, fit(sec["note"], 8.5, W - 2 * M), 8.5, color=mute)
            st["y"] += 16
        if sec.get("cols") and sec.get("rows") is not None:
            table(sec["cols"], sec["rows"], sec.get("row_colours"))
    footers()
    return pdf.output()


def to_csv(header: list[str], rows: list[list[Any]]) -> bytes:
    import csv
    import io
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(header)
    for r in rows:
        w.writerow(["" if c is None else c for c in r])
    return buf.getvalue().encode("utf-8-sig")       # BOM so Excel reads UTF-8


def _slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", str(s).lower()).strip("-") or "report"


# --------------------------------------------------------------------------
class ReportsManager:
    def __init__(self, hass: "HomeAssistant", entry: "ConfigEntry", hub: Any) -> None:
        from homeassistant.helpers.storage import Store
        self.hass, self.entry, self.hub = hass, entry, hub
        self.store = Store(hass, STORAGE_VERSION, f"{DOMAIN}.reports_{entry.entry_id}")
        self.data: dict[str, Any] = {"reports": []}

    async def async_start(self) -> None:
        self.data = await self.store.async_load() or {"reports": []}

    async def async_stop(self) -> None:
        return

    # ---- read side -------------------------------------------------------
    def types(self) -> list[dict[str, Any]]:
        return R.types_public()

    def recent(self, n: int = 60) -> list[dict[str, Any]]:
        own = list(self.data.get("reports", []))
        comp = [self._from_compliance(r) for r in self._compliance_reports()]
        return R.merge_records(own, comp, limit=n)

    def _compliance_reports(self) -> list[dict[str, Any]]:
        mgr = getattr(self.hub, "compliance", None)
        try:
            return mgr.reports(40) if mgr else []
        except Exception:  # noqa: BLE001
            return []

    @staticmethod
    def _from_compliance(r: dict[str, Any]) -> dict[str, Any]:
        bad = r.get("status") != "compliant"
        return R.make_record("cold_chain", period=r.get("period") or "", created=r.get("created") or "",
                             status="warn" if bad else "ok", fmt="pdf", url=r.get("url"), path=r.get("path"),
                             summary=f"{r.get('unit', '')}: {r.get('status', '')}"
                                     + (f", {r.get('excursions')} excursion(s)" if r.get("excursions") else ""),
                             rid=(r.get("url") or r.get("path")))

    # ---- write side ------------------------------------------------------
    async def async_generate(self, type_id: str, *, period: str = "week", start: datetime | None = None,
                             end: datetime | None = None, scope: str = "site", fmt: str = "pdf") -> dict[str, Any]:
        t = R.BY_ID.get(type_id)
        if t is None:
            return {"ok": False, "message": f"Unknown report '{type_id}'"}
        if t.status == "soon":
            return {"ok": False, "message": f"{t.title} is coming soon."}
        from homeassistant.util import dt as dt_util
        tz = dt_util.DEFAULT_TIME_ZONE
        s, e, label = R.resolve_period(period, dt_util.now(), start, end)
        if type_id == "cold_chain":
            return await self._gen_cold_chain(period, s, e, label)
        if type_id == "device_health":
            return await self._gen_device_health(label, s, e, fmt, tz)
        return {"ok": False, "message": f"{t.title} is not available yet."}

    async def _gen_cold_chain(self, period: str, s: datetime, e: datetime, label: str) -> dict[str, Any]:
        mgr = getattr(self.hub, "compliance", None)
        if mgr is None:
            return {"ok": False, "message": "Cold-chain reporting is not set up."}
        kind = period if period in ("week", "month") else "custom"
        res = await mgr.async_create(kind, start=s, end=e, send=False)
        reps = res.get("reports", [])
        from homeassistant.helpers.dispatcher import async_dispatcher_send
        async_dispatcher_send(self.hass, SIGNAL_REPORTS.format(self.entry.entry_id))
        return {"ok": True, "message": f"{len(reps)} cold-chain record(s) for {label}.", "count": len(reps)}

    async def _gen_device_health(self, label: str, s: datetime, e: datetime, fmt: str, tz: tzinfo) -> dict[str, Any]:
        from .fleet import fleet_devices
        from homeassistant.util import dt as dt_util
        devices = fleet_devices(self.hass, self.entry)
        now = dt_util.now()
        online = sum(1 for d in devices if d["online"])
        low = sum(1 for d in devices if d.get("battery_low"))
        off = [d for d in devices if not d["online"]]
        site = (self.entry.title or "Site")

        def _last(d: dict) -> str:
            ls = d.get("last_seen")
            if not ls:
                return "never"
            try:
                return dt_util.as_local(dt_util.parse_datetime(ls)).strftime("%d %b %H:%M")
            except Exception:  # noqa: BLE001
                return "—"

        rows = [[d["name"], d["model"], d.get("area") or "—", "Online" if d["online"] else "Offline",
                 _last(d), "—" if d.get("battery") is None else f"{d['battery']}%",
                 "—" if d.get("rssi") is None else f"{d['rssi']} dBm",
                 "—" if d.get("snr") is None else f"{d['snr']} dB"] for d in devices]
        colours = [None if d["online"] else "#c62828" for d in devices]
        created = now.isoformat()
        token = created[-6:].replace(":", "")
        name = f"device-health-{s:%Y%m%d}-{token}.{fmt}"
        folder = self.hass.config.path("www", "milesight", "reports", f"{s:%Y}")
        url = f"/local/milesight/reports/{s:%Y}/{name}"

        if fmt == "csv":
            data = to_csv(["Device", "Model", "Area", "Status", "Last seen", "Battery", "RSSI", "SNR",
                           "Offline hours"],
                          [[d["name"], d["model"], d.get("area") or "", "Online" if d["online"] else "Offline",
                            _last(d), d.get("battery"), d.get("rssi"), d.get("snr"),
                            d.get("offline_hours")] for d in devices])
        else:
            summary = [{"heading": "Fleet summary", "cols": [("Metric", 240, "left"), ("Value", 240, "right")],
                        "rows": [["Devices", str(len(devices))], ["Online now", f"{online} / {len(devices)}"],
                                 ["Offline now", str(len(off))], ["Low battery", str(low)]]}]
            health = [{"heading": "Devices",
                       "cols": [("Device", 120, "left"), ("Model", 70, "left"), ("Area", 70, "left"),
                                ("Status", 52, "left"), ("Last seen", 70, "left"), ("Batt", 42, "right"),
                                ("RSSI", 52, "right"), ("SNR", 40, "right")],
                       "rows": rows, "row_colours": colours}]
            status = ("ALL ONLINE" if not off else f"{len(off)} OFFLINE",
                      "#2e7d32" if not off else "#c62828")
            data = build_pdf("Device health & uptime", site, label, summary + health,
                             author=site, status=status)

        def _write() -> None:
            import os
            os.makedirs(folder, exist_ok=True)
            with open(f"{folder}/{name}", "wb") as f:
                f.write(data)
        await self.hass.async_add_executor_job(_write)

        rec = R.make_record("device_health", period=label, created=created,
                            status="ok" if not off else "warn", fmt=fmt, url=url,
                            path=f"{folder}/{name}", size=len(data),
                            summary=f"{online}/{len(devices)} online"
                                    + (f", {len(off)} offline" if off else "") + (f", {low} low battery" if low else ""))
        self._save(rec)
        return {"ok": True, "message": rec["summary"], "record": rec}

    def _save(self, rec: dict[str, Any]) -> None:
        self.data.setdefault("reports", [])[:0] = [rec]
        del self.data["reports"][KEEP:]
        self.hass.async_create_task(self.store.async_save(self.data))
        from homeassistant.helpers.dispatcher import async_dispatcher_send
        async_dispatcher_send(self.hass, SIGNAL_REPORTS.format(self.entry.entry_id))
