"""Reports hub — the Home Assistant glue for the reporting framework (reports.py).

One manager per gateway. It owns an index of generated reports, renders PDFs / CSVs with the dependency-free
writer (pdfmini.py), writes them under ``www/milesight/reports/<year>/`` (served at ``/local/…``) and lists what
exists for the Reports page. Cold-chain reports are produced by the existing ComplianceManager and folded into
the same library, so the page shows every report type in one place.
"""
